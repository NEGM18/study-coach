-- 0001_init.sql — first app schema (issue #36, W2-02).
-- Column names match ml_core/schemas.py exactly: Attempt -> quiz_attempts, Chunk -> lecture_chunks,
-- Topic -> course_topics, TopicMastery -> topic_mastery. Never edit this file after it is applied;
-- add 0002_... instead.
--
-- Access model:
--   * The app uses the anon key + the student's JWT, so Row Level Security below decides what it sees.
--   * The API and worker use the service-role key (server only), which bypasses RLS to write
--     lectures, chunks, jobs and topic_mastery.

begin;

-- ---------------------------------------------------------------- users and courses

create table public.users (
    user_id     uuid primary key references auth.users (id) on delete cascade,
    locale      text not null default 'ar' check (locale in ('ar', 'en')),
    created_at  timestamptz not null default now()
);

create table public.courses (
    course_id    integer primary key,
    code         text not null unique,
    name         text not null,
    name_ar      text not null default '',
    description  text not null default '',
    created_at   timestamptz not null default now()
);

create table public.course_members (
    course_id   integer not null references public.courses (course_id) on delete cascade,
    user_id     uuid not null references public.users (user_id) on delete cascade,
    role        text not null default 'student' check (role in ('student', 'admin')),
    joined_at   timestamptz not null default now(),
    primary key (course_id, user_id)
);

create table public.course_topics (
    topic_id     integer primary key,
    course_id    integer not null references public.courses (course_id) on delete cascade,
    name         text not null,
    description  text not null default '',
    unique (course_id, name)
);

-- ---------------------------------------------------------------- lectures and chunks

create table public.lectures (
    lecture_id    integer generated by default as identity primary key,
    course_id     integer not null references public.courses (course_id) on delete cascade,
    uploaded_by   uuid references public.users (user_id) on delete set null,
    title         text not null default '',
    source_type   text not null check (source_type in ('audio', 'slides', 'pdf')),
    storage_path  text not null,
    status        text not null default 'pending'
                  check (status in ('pending', 'processing', 'done', 'failed')),
    created_at    timestamptz not null default now()
);

create table public.lecture_chunks (
    chunk_id          text primary key,
    course_id         integer not null references public.courses (course_id) on delete cascade,
    lecture_id        integer not null references public.lectures (lecture_id) on delete cascade,
    text              text not null,
    slide_no          integer,
    lang              text not null default 'ar' check (lang in ('ar', 'en', 'mixed')),
    topic_id          integer references public.course_topics (topic_id) on delete set null,
    topic_confidence  real check (topic_confidence between 0 and 1),
    start_s           real,
    end_s             real,
    created_at        timestamptz not null default now()
);
create index lecture_chunks_lecture_idx on public.lecture_chunks (lecture_id);

-- ---------------------------------------------------------------- quizzes and mastery

create table public.quiz_questions (
    question_id   integer generated by default as identity primary key,
    course_id     integer not null references public.courses (course_id) on delete cascade,
    topic_id      integer not null references public.course_topics (topic_id) on delete cascade,
    lecture_id    integer references public.lectures (lecture_id) on delete set null,
    stem          text not null,
    choices       jsonb not null default '[]'::jsonb,
    answer_index  integer not null,
    created_at    timestamptz not null default now()
);

create table public.quiz_attempts (
    attempt_id        bigint generated by default as identity primary key,
    user_id           uuid not null references public.users (user_id) on delete cascade,
    topic_id          integer not null references public.course_topics (topic_id) on delete cascade,
    question_id       integer not null references public.quiz_questions (question_id) on delete cascade,
    attempt_order     integer not null check (attempt_order >= 1),
    is_correct        boolean not null,
    response_time_ms  integer check (response_time_ms > 0),
    attempt_count     integer not null default 1,
    hint_count        integer not null default 0,
    created_at        timestamptz not null default now(),
    unique (user_id, attempt_order)
);
create index quiz_attempts_user_topic_idx on public.quiz_attempts (user_id, topic_id);

create table public.topic_mastery (
    user_id     uuid not null references public.users (user_id) on delete cascade,
    topic_id    integer not null references public.course_topics (topic_id) on delete cascade,
    mastery     real not null check (mastery between 0 and 1),
    updated_at  timestamptz not null default now(),
    primary key (user_id, topic_id)
);

-- ---------------------------------------------------------------- worker queue

create table public.jobs (
    job_id      bigint generated by default as identity primary key,
    job_type    text not null check (job_type in ('lecture_audio', 'lecture_slides', 'quiz_attempt')),
    status      text not null default 'pending'
                check (status in ('pending', 'running', 'done', 'failed')),
    lecture_id  integer references public.lectures (lecture_id) on delete cascade,
    created_by  uuid references public.users (user_id) on delete set null,
    payload     jsonb not null default '{}'::jsonb,
    error       text,
    tries       integer not null default 0,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);
create index jobs_pending_idx on public.jobs (created_at) where status = 'pending';

-- ---------------------------------------------------------------- new sign-ups get a users row

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    insert into public.users (user_id) values (new.id) on conflict do nothing;
    return new;
end;
$$;

create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------- row level security

create function public.is_course_member(target_course_id integer) returns boolean
language sql stable security definer set search_path = '' as $$
    select exists (
        select 1 from public.course_members m
        where m.course_id = target_course_id and m.user_id = (select auth.uid())
    );
$$;

alter table public.users          enable row level security;
alter table public.courses        enable row level security;
alter table public.course_members enable row level security;
alter table public.course_topics  enable row level security;
alter table public.lectures       enable row level security;
alter table public.lecture_chunks enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.quiz_attempts  enable row level security;
alter table public.topic_mastery  enable row level security;
alter table public.jobs           enable row level security;

create policy users_own on public.users
    for all to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy courses_read on public.courses
    for select to authenticated using (true);

create policy members_read_own on public.course_members
    for select to authenticated using (user_id = (select auth.uid()));
create policy members_join_self on public.course_members
    for insert to authenticated with check (user_id = (select auth.uid()) and role = 'student');

create policy topics_read_members on public.course_topics
    for select to authenticated using (public.is_course_member(course_id));

create policy lectures_read_members on public.lectures
    for select to authenticated using (public.is_course_member(course_id));

create policy chunks_read_members on public.lecture_chunks
    for select to authenticated using (public.is_course_member(course_id));

create policy questions_read_members on public.quiz_questions
    for select to authenticated using (public.is_course_member(course_id));

create policy attempts_read_own on public.quiz_attempts
    for select to authenticated using (user_id = (select auth.uid()));
create policy attempts_insert_own on public.quiz_attempts
    for insert to authenticated with check (user_id = (select auth.uid()));

create policy mastery_read_own on public.topic_mastery
    for select to authenticated using (user_id = (select auth.uid()));

create policy jobs_read_own on public.jobs
    for select to authenticated using (created_by = (select auth.uid()));

commit;
